/**
 * Get the WHO reference data array for a given metric and gender.
 *
 * @param {('weight'|'height'|'head'|'bmi')} metric
 * @param {('male'|'female'|'m'|'f')} gender
 * @returns {Array<{age:number,p3:number,p15:number,p50:number,p85:number,p97:number}>}
 */
export function getWhoReferenceData(metric, gender) {
    const isGirl = gender === 'female' || gender === 'f' || gender === 'F';
    if (metric === 'weight') return isGirl ? WHO_WEIGHT_GIRLS : WHO_WEIGHT_BOYS;
    if (metric === 'height') return isGirl ? WHO_HEIGHT_GIRLS : WHO_HEIGHT_BOYS;
    if (metric === 'head')   return isGirl ? WHO_HEAD_GIRLS   : WHO_HEAD_BOYS;
    if (metric === 'bmi')    return isGirl ? WHO_BMI_GIRLS    : WHO_BMI_BOYS;
    return [];
}
